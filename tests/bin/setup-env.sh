#!/usr/bin/env bash
# Builds a disposable WordPress + WooCommerce test site on SQLite (no MySQL needed) and links this plugin into it.
#
#   tests/bin/setup-env.sh <target-dir> [site-url]
#
# Needs: php (with pdo_sqlite), git, composer, curl, python3.
# Versions can be overridden with WP_VERSION / WC_VERSION / SQLITE_VERSION.
set -euo pipefail

TARGET=${1:?usage: setup-env.sh <target-dir> [site-url]}
URL=${2:-http://127.0.0.1:8899/site}
WP_VERSION=${WP_VERSION:-7.1.2}
WC_VERSION=${WC_VERSION:-11.1.2}
SQLITE_VERSION=${SQLITE_VERSION:-v3.0.2}
PLUGIN_DIR=$(cd "$(dirname "$0")/../.." && pwd)

mkdir -p "$TARGET"
TARGET=$(cd "$TARGET" && pwd)
cd "$TARGET"

[ -d wp ] || git clone -q --depth 1 --branch "$WP_VERSION" https://github.com/WordPress/WordPress wp
[ -d sqlite ] || git clone -q --depth 1 --branch "$SQLITE_VERSION" https://github.com/WordPress/sqlite-database-integration sqlite
if [ ! -d wcrepo ]; then
  git clone -q --depth 1 --filter=blob:none --sparse --branch "$WC_VERSION" https://github.com/woocommerce/woocommerce wcrepo
  (cd wcrepo && git sparse-checkout set plugins/woocommerce packages/php)
fi

WC="$TARGET/wcrepo/plugins/woocommerce"
if [ ! -d "$WC/vendor" ]; then
  (cd "$WC" && COMPOSER_ALLOW_SUPERUSER=1 composer install --no-dev --prefer-source -q)
fi
# Generated by WooCommerce's JS build in release zips.
if [ ! -f "$WC/includes/react-admin/feature-config.php" ]; then
  (cd "$WC" && WC_ADMIN_PHASE=core php bin/generate-feature-config.php)
fi
# Without the JS build the admin asset registry files are missing: stub them instead of throwing (test sites only).
python3 "$PLUGIN_DIR/tests/bin/stub-wc-assets.py" "$WC/src/Internal/Admin/WCAdminAssets.php"

[ -f wp-cli.phar ] || curl -sSL -o wp-cli.phar https://github.com/wp-cli/wp-cli/releases/download/v2.12.0/wp-cli-2.12.0.phar

rm -rf site && mkdir site
(cd wp && tar --exclude=.git -cf - .) | (cd site && tar -xf -)

P=site/wp-content/plugins/sqlite-database-integration
cp -r sqlite/packages/plugin-sqlite-database-integration "$P"
rm -rf "$P/wp-includes/database"
cp -r sqlite/packages/mysql-on-sqlite/src "$P/wp-includes/database"
sed -e "s#'{SQLITE_IMPLEMENTATION_FOLDER_PATH}'#__DIR__.'/plugins/sqlite-database-integration'#g" \
    -e "s#{SQLITE_PLUGIN}#sqlite-database-integration/load.php#g" "$P/db.copy" > site/wp-content/db.php

ln -s "$WC" site/wp-content/plugins/woocommerce
ln -s "$PLUGIN_DIR" site/wp-content/plugins/lp-missing
cp "$PLUGIN_DIR/tests/bin/wp-config-test.php" site/wp-config.php

WP="php $TARGET/wp-cli.phar --allow-root --path=$TARGET/site"
$WP core install --url="$URL" --title=Test --admin_user=admin --admin_password=admin --admin_email=admin@example.com --skip-email
$WP plugin activate woocommerce lp-missing
echo "Ready. Run: $WP eval-file $PLUGIN_DIR/tests/integration/test-plugin.php"
